#!/usr/bin/env node
/**
 * assets/ui/icons/manifest.json (written by post.py + vector.py) → src/ui/icon-manifest.js, the compact table the
 * HUD imports (no fetch at boot, so the icons can be preloaded with the HUD and laid out before they decode).
 *
 *   node tools/blender/icons/gen-manifest.mjs
 *
 * Entry: 'class/id': { b: [w, h] ref box, t: { tier: [w, h, png?1:0] }, h?: [x, y] hotspot in ref-box units, v?: 1 vector,
 *   s?: knapsack slots the item spans (1, or 2 for long guns; the box already carries the equal-visual-mass size) }
 * Tier keys are the pixel density over the ref box: items/tools/stamps '2x'…'6x', cursors '1x'…'3x' ('1p5x' = 1.5).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const src = JSON.parse(readFileSync(join(ROOT, 'assets/ui/icons/manifest.json'), 'utf8'));
const dens = (k) => Number(k.replace('x', '').replace('p', '.'));
const out = {};
for (const id of Object.keys(src).sort()) {
  const e = src[id];
  const t = {};
  let hot = null;
  const tiers = Object.keys(e.files).sort((a, b) => dens(a) - dens(b));
  for (const k of tiers) {
    const f = e.files[k];
    t[k] = [f.w, f.h, f.png ? 1 : 0];
    if (!hot && f.hot) hot = f.hot.map((v) => Math.round((v / dens(k)) * 100) / 100);
  }
  out[id] = { b: e.box, t, ...(hot ? { h: hot } : {}), ...(e.vector ? { v: 1 } : {}), ...(e.slot ? { s: e.slot } : {}) };
}
const body = Object.entries(out).map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`).join('\n');
const js = `/**
 * GENERATED by tools/blender/icons/gen-manifest.mjs from assets/ui/icons/manifest.json. Do not edit by hand.
 * 'class/id' → { b: ref box [w, h], t: { tier: [w, h, hasPng] }, h?: hotspot in ref-box units, v?: vector art, s?: pack slots }.
 * @module ui/icon-manifest
 */
export const ICON_MANIFEST = {
${body}
};
`;
writeFileSync(join(ROOT, 'src/ui/icon-manifest.js'), js);
console.log(`icon-manifest.js: ${Object.keys(out).length} icons`);
