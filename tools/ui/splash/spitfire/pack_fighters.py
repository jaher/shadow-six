#!/usr/bin/env python3
"""Pack the dogfight turntable (render.py ... turntable) into the main menu's fighter atlas:
assets/ui/keyart/fighters.webp + the generated layout src/ui/fighter-atlas.js, and a contact sheet.
Cells are halved (premultiplied Lanczos), hazed a little toward the menu stills' sky, trimmed and shelf-packed.
    python3 pack_fighters.py <outdir> [--sheet <jpg>] [--q 78] [--aq 60]
"""
import json, os, sys
import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..', '..'))
HAZE, HAZE_K, GAP, WIDTH, SCALE = (205, 200, 178), 0.14, 2, 1024, 0.4   # cells at 0.4x the render (7.2 px / m)
X_YAW, X_BANK = (-45.0, -22.5, 0.0, 22.5, 45.0), (-60.0, 0.0, 60.0)       # the hit 109's (smaller) set


def arg(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default


def load(path):
    im = Image.open(path).convert('RGBA').convert('RGBa')
    im = im.resize((round(im.width * SCALE), round(im.height * SCALE)), Image.LANCZOS)
    a = np.asarray(im).astype(np.float32)
    a[..., :3] = a[..., :3] * (1 - HAZE_K) + np.array(HAZE, np.float32) * HAZE_K * a[..., 3:] / 255
    im = Image.fromarray(np.clip(a + 0.5, 0, 255).astype(np.uint8), 'RGBa').convert('RGBA')
    box = im.getchannel('A').point(lambda v: 255 if v > 3 else 0).getbbox()
    x0, y0 = max(0, box[0] - GAP), max(0, box[1] - GAP)
    return im.crop((x0, y0, min(im.width, box[2] + GAP), min(im.height, box[3] + GAP))), (x0, y0)


def main():
    src = os.path.join(sys.argv[1], 'turntable')
    meta = json.load(open(os.path.join(src, 'meta.json')))
    kinds, cells = ('spit', 'bf109', 'bf109x'), []
    for kind in kinds:
        for yaw in (X_YAW if kind == 'bf109x' else meta['yaw']):
            for bank in (X_BANK if kind == 'bf109x' else meta['bank']):
                key = '%s_%g_%g' % (kind, yaw, bank)
                im, (ox, oy) = load(os.path.join(src, key + '.png'))
                m = meta['cells'][key]
                ax, ay = m['anchor'][0] * SCALE - ox, m['anchor'][1] * SCALE - oy
                rel = lambda p: [round(p[0] * SCALE - ox - ax, 1), round(p[1] * SCALE - oy - ay, 1)]
                cells.append({'kind': kind, 'key': key, 'im': im, 'a': [round(ax, 1), round(ay, 1)],
                              'pts': rel(m['nose']) + rel(m['tail']) + rel(m['engine'])})
    # shelf packing, tallest first
    order = sorted(range(len(cells)), key=lambda i: -cells[i]['im'].height)
    x = y = shelf = 0
    for i in order:
        im = cells[i]['im']
        if x + im.width + GAP > WIDTH:
            x, y, shelf = 0, y + shelf + GAP, 0
        cells[i]['xy'] = (x + GAP, y + GAP)
        x += im.width + GAP
        shelf = max(shelf, im.height)
    H = y + shelf + 2 * GAP
    atlas = Image.new('RGBA', (WIDTH, H), (0, 0, 0, 0))
    for c in cells:
        atlas.paste(c['im'], c['xy'])
    out = os.path.join(ROOT, 'assets/ui/keyart/fighters.webp')
    atlas.save(out, 'WEBP', quality=int(arg('--q', 78)), alpha_quality=int(arg('--aq', 60)), method=6, exact=True)
    rows = []
    for kind in kinds:
        lst = [c for c in cells if c['kind'] == kind]
        rows.append('    %s: [\n%s,\n    ]' % (kind, ',\n'.join('      [%d, %d, %d, %d, %s, %s, %s]' % (
            c['xy'][0], c['xy'][1], c['im'].width, c['im'].height, c['a'][0], c['a'][1], ', '.join('%g' % v for v in c['pts'])) for c in lst)))
    js = os.path.join(ROOT, 'src/ui/fighter-atlas.js')
    with open(js, 'w') as fh:
        fh.write('''/**
 * GENERATED by tools/ui/splash/spitfire/pack_fighters.py (do not edit): the main menu's dogfight sprites,
 * assets/ui/keyart/fighters.webp, rendered by render.py ... turntable from model.py (Spitfire LF Mk IX) and bf109.py
 * (Bf 109 G-6) in the menu stills' daylight, seen %g deg from below. Each type has yaw x bank cells (index
 * yaw * %d + bank): yaw + = nose toward the viewer, bank + = near wing down; the runtime mirrors them for the other half
 * of the circle and turns them in the screen plane for pitch. bf109x: the hit 109, smoke-blackened, on its own
 * smaller grid (xyaw x xbank).
 * Cell: [x, y, w, h, ax, ay, nose x, y, tail x, y, engine x, y]: (ax, ay) the anchor (the wing centre section) in
 * the cell, the points relative to it, atlas px. pxm: atlas px per metre; len: each type's length (m).
 * @module ui/fighter-atlas
 */
export const FIGHTER_ATLAS = {
  url: 'assets/ui/keyart/fighters.webp', w: %d, h: %d, pxm: %g,
  yaw: %s, bank: %s, xyaw: %s, xbank: %s, len: { spit: %g, bf109: %g },
  cells: {
%s,
  },
};
''' % (meta['elev'], len(meta['bank']), WIDTH, H, meta['k2'] * SCALE, json.dumps(meta['yaw']), json.dumps(meta['bank']),
       json.dumps(list(X_YAW)), json.dumps(list(X_BANK)), meta['len']['spit'], meta['len']['bf109'], ',\n'.join(rows)))
    print('atlas %dx%d, %d bytes -> %s' % (WIDTH, H, os.path.getsize(out), out))
    sheet = arg('--sheet')
    if sheet:
        s = atlas.copy()
        bg = Image.new('RGBA', s.size, (205, 200, 178, 255))
        bg.alpha_composite(s)
        bg.convert('RGB').save(sheet, quality=88)
        print('sheet ->', sheet)


if __name__ == '__main__':
    main()
