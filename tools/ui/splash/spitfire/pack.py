#!/usr/bin/env python3
"""Packs the Spitfire cells rendered by render.py into the splash sprite atlas.

  python3 tools/ui/splash/spitfire/pack.py <render outdir> [--sheet <contact.jpg>] [--q 90]

Reads <outdir>/cells/<pose>_<state>.png (2x scale) + meta.json; downsamples 2x in premultiplied alpha, crops each
cell to its alpha box, packs poses in rows (loaded | clean), and writes assets/ui/keyart/spitfires.webp plus the
generated layout module src/ui/spitfire-atlas.js (cell rects, the anchor = the belly-bomb station, px per metre).
--sheet also writes a contact sheet (cells enlarged and at their on-screen sizes over the splash sky colour, and the
neutral reference views from <outdir>/views).
"""
import json, os, sys
import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../../..'))
POSES, STATES = ('a', 'b', 'c'), ('loaded', 'half', 'clean')
GAP = 2


def arg(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default


HAZE = (30, 33, 37)     # the splash sky around the flight corridor: a touch of aerial perspective


def load_cell(path, haze):
    im = Image.open(path).convert('RGBA').convert('RGBa')           # premultiplied for the resample
    im = im.resize((im.width // 2, im.height // 2), Image.LANCZOS)
    a = np.asarray(im).astype(np.float32)
    a[..., :3] = a[..., :3] * (1 - haze) + np.array(HAZE, np.float32) * haze * a[..., 3:] / 255
    im = Image.fromarray(np.clip(a + 0.5, 0, 255).astype(np.uint8), 'RGBa').convert('RGBA')
    box = im.getchannel('A').point(lambda a: 255 if a > 3 else 0).getbbox()
    x0, y0 = max(0, box[0] - GAP), max(0, box[1] - GAP)
    x1, y1 = min(im.width, box[2] + GAP), min(im.height, box[3] + GAP)
    return im.crop((x0, y0, x1, y1)), (x0, y0)


def main():
    src = sys.argv[1]
    meta = json.load(open(os.path.join(src, 'cells', 'meta.json')))
    cells, layout = {}, {}
    haze = float(arg('--haze', 0.08))
    for p in POSES:
        for s in STATES:
            cells[(p, s)] = load_cell(os.path.join(src, 'cells', '%s_%s.png' % (p, s)), haze)
    bomb, (box, boy) = load_cell(os.path.join(src, 'cells', 'bomb.png'), haze)
    # the lone falling bomb reads in silhouette against the brighter sky (its lit underside turns away as it noses
    # down): darkened, so a true-scale 250 lb bomb (a few px) still shows as a dark speck
    b = np.asarray(bomb).astype(np.float32)
    b[..., :3] *= 0.4
    bomb = Image.fromarray(np.clip(b + 0.5, 0, 255).astype(np.uint8), 'RGBA')
    col_w = [max(cells[(p, s)][0].width for p in POSES) for s in STATES]
    row_h = [max(cells[(p, s)][0].height for s in STATES) for p in POSES]
    W, H = sum(col_w) + GAP * (len(STATES) + 1), sum(row_h) + GAP * (len(POSES) + 2) + bomb.height
    atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    y = GAP
    for r, p in enumerate(POSES):
        x = GAP
        layout[p] = {}
        for c, s in enumerate(STATES):
            im, (ox, oy) = cells[(p, s)]
            atlas.paste(im, (x, y))
            pm = meta['poses'][p]
            ax, ay = pm['anchor'][0] / 2 - ox, pm['anchor'][1] / 2 - oy
            layout[p][s] = [x, y, im.width, im.height, round(ax, 1), round(ay, 1)]
            x += col_w[c] + GAP
        # wing hardpoints (near = starboard, far = port) relative to the anchor, atlas px
        layout[p]['hp'] = [[round((pm[k][0] - pm['anchor'][0]) / 2, 1), round((pm[k][1] - pm['anchor'][1]) / 2, 1)]
                           for k in ('hp_near', 'hp_far')]
        y += row_h[r] + GAP
    atlas.paste(bomb, (GAP, y))
    bo = meta['bomb']['origin']
    layout['bomb'] = [GAP, y, bomb.width, bomb.height, round(bo[0] / 2 - box, 1), round(bo[1] / 2 - boy, 1)]
    pxm = meta['k2'] / 2
    out = os.path.join(ROOT, 'assets/ui/keyart/spitfires.webp')
    q = int(arg('--q', 90))
    atlas.save(out, 'WEBP', quality=q, alpha_quality=100, method=6, exact=True)
    atlas.save(os.path.join(src, 'atlas.png'))
    js = os.path.join(ROOT, 'src/ui/spitfire-atlas.js')
    rows = ',\n'.join('    %s: { %s, hp: %s }' % (p, ', '.join('%s: %s' % (st, json.dumps(layout[p][st])) for st in STATES),
                                                  json.dumps(layout[p]['hp'])) for p in POSES)
    with open(js, 'w') as fh:
        fh.write('''/**
 * GENERATED by tools/ui/splash/spitfire/pack.py (do not edit): the title splash's Spitfire sprite atlas,
 * assets/ui/keyart/spitfires.webp, rendered by tools/ui/splash/spitfire/render.py from the model in model.py.
 * Poses (yaw / pitch / bank, deg): %s. Each pose has three load states: loaded (a 250 lb bomb under each
 * wing), half (the near, starboard bomb gone) and clean. Cell: [x, y, w, h, ax, ay] in atlas px; (ax, ay) is the
 * anchor in the cell (the belly station under the wing centre section). hp: the near and far wing hardpoints
 * (bomb centres) relative to the anchor, atlas px. bomb: the falling 250 lb bomb, nose right, anchored at its
 * centre; bombLen its length with the tail (m). pxm: atlas px per metre; len: the Spitfire (spinner to rudder, m).
 * @module ui/spitfire-atlas
 */
export const SPITFIRE_ATLAS = {
  url: 'assets/ui/keyart/spitfires.webp', w: %d, h: %d, pxm: %s, len: 9.47, bombLen: %s,
  cells: {
%s,
  },
  bomb: %s,
};
''' % ('; '.join('%s %g/%g/%g' % (p, meta['poses'][p]['yaw'], meta['poses'][p]['pitch'], meta['poses'][p]['bank']) for p in POSES),
       W, H, pxm, meta['bombLen'], rows, json.dumps(layout['bomb'])))
    print('atlas %dx%d, %d bytes -> %s' % (W, H, os.path.getsize(out), out))
    sheet = arg('--sheet')
    if sheet:
        contact(src, atlas, layout, pxm, sheet)


def contact(src, atlas, layout, pxm, path):
    from PIL import ImageDraw
    bg = (24, 27, 30)
    sheet = Image.new('RGB', (1280, 1400), bg)
    d = ImageDraw.Draw(sheet)
    x, y = 16, 16
    for p in POSES:                                     # cells at 2x the atlas scale
        for s in STATES:
            cx, cy, w, h, _, _ = layout[p][s]
            im = atlas.crop((cx, cy, cx + w, cy + h))
            im = im.resize((w * 2, h * 2), Image.LANCZOS)
            sheet.paste(im, (x, y), im)
            d.text((x, y), '%s %s' % (p, s), fill=(150, 150, 150))
            x += w * 2 + 16
        x, y = 16, y + max(layout[p][s][3] for s in STATES) * 2 + 8
    bx, by, bw, bh = layout['bomb'][:4]                  # the falling 250 lb bomb, 4x
    im = atlas.crop((bx, by, bx + bw, by + bh)).resize((bw * 4, bh * 4), Image.LANCZOS)
    tile = Image.new('RGB', im.size, (70, 74, 80))
    tile.paste(im, (0, 0), im)
    sheet.paste(tile, (16, y))
    d.text((16 + bw * 4 + 10, y + bh), 'falling 250 lb bomb (4x; darkened: seen in silhouette)', fill=(150, 150, 150))
    y += bh * 4 + 12
    for target in (44, 64, 100):                         # at on-screen sizes: 1080p, 1440p, 4K-ish leaders
        x = 16
        for p in POSES:
            cx, cy, w, h, _, _ = layout[p]['loaded']
            k = target / (9.47 * pxm)
            im = atlas.crop((cx, cy, cx + w, cy + h)).convert('RGBa')
            im = im.resize((max(1, round(w * k)), max(1, round(h * k))), Image.LANCZOS).convert('RGBA')
            sheet.paste(im, (x, y), im)
            x += im.width + 24
        d.text((x, y), '%d px long' % target, fill=(150, 150, 150))
        y += round(max(layout[p]['clean'][3] for p in POSES) * target / (9.47 * pxm)) + 10
    vdir = os.path.join(src, 'views')
    if os.path.isdir(vdir):                              # neutral reference views of the model
        d.text((16, y), 'model, neutral light: starboard side, front, three-quarter, plan, underside', fill=(150, 150, 150))
        y += 16
        rows = ((('side', (620, 230)), ('front', (300, 230)), ('three_q', (310, 230))),
                (('plan', (620, 400)), ('under', (620, 400))))
        for row in rows:
            x, hmax = 16, 0
            for name, box in row:
                f = os.path.join(vdir, name + '.png')
                if not os.path.exists(f):
                    continue
                im = Image.open(f).convert('RGBA')
                im = im.crop(im.getchannel('A').getbbox())
                im.thumbnail(box, Image.LANCZOS)
                tile = Image.new('RGB', box, (82, 86, 92))
                tile.paste(im, ((box[0] - im.width) // 2, (box[1] - im.height) // 2), im)
                sheet.paste(tile, (x, y))
                x += box[0] + 8
                hmax = max(hmax, box[1])
            y += hmax + 8
    sheet = sheet.crop((0, 0, 1280, min(sheet.height, y)))
    sheet.save(path, quality=88)
    print('sheet ->', path)


if __name__ == '__main__':
    main()
