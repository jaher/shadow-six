/**
 * Writes dist/sw.js + dist/sw-index-<hash>.json: a service worker that keeps the large, immutable-per-content assets
 * (models, textures, audio, video, fonts, decoders) in Cache Storage across visits, so a returning player — or a
 * mission restarted after a page reload — loads them with no network request (offline play once downloaded).
 *
 * - Assets (`ss-assets-v1`): cache-first, keyed by URL + content hash from the index, so an asset that changes in a
 *   deploy misses the cache and is fetched fresh while every unchanged file keeps its entry; entries not in the new
 *   index are purged on activate. Range requests (media elements) are answered from a cached copy when there is one;
 *   otherwise they stream from the network while the whole file is stored for next time. A miss is fetched with
 *   `cache: 'no-cache'` (Pages sends max-age=600: a deploy can land while the browser still holds the old file fresh) and
 *   only stored when its SHA-1 matches the index hash, so an old copy never lands under the new key.
 * - Code, HTML, CSS, JSON (`ss-code-<version>`, per build): network-first, so they are never stale; this build's copy
 *   is only the offline fallback. Older builds' code caches are deleted on activate.
 * - Messages from the page (engine/offline-cache.js): `cache-urls` stores assets the page loaded before the worker
 *   controlled it; `prefetch` stores a mission ahead at low priority; `status` reports the cached asset count.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const CACHEABLE = /\.(glb|webp|jpe?g|png|hdr|ogg|mp3|webm|mp4|woff2?|ttf|cube|wasm|svg)$/i;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...await walk(p)); else out.push(p);
  }
  return out;
}

export async function writeServiceWorker(out, info) {
  const index = {};
  for (const f of await walk(out)) {
    const rel = relative(out, f).split('\\').join('/');
    if (!CACHEABLE.test(rel) || !/^(assets|vendor)\//.test(rel)) continue;
    index[rel] = createHash('sha1').update(await readFile(f)).digest('hex').slice(0, 12);
  }
  const json = JSON.stringify(index);
  const ih = createHash('sha1').update(json).digest('hex').slice(0, 12);
  const indexFile = `sw-index-${ih}.json`;
  await writeFile(join(out, indexFile), json);
  await writeFile(join(out, 'sw.js'), swSource(info.short, indexFile));
  return { cached: Object.keys(index).length };
}

function swSource(version, indexFile) {
  return `/* SHADOW SIX cache, build ${version}. Generated by tools/build/sw.mjs. */
const VERSION = ${JSON.stringify(version)};
const INDEX_URL = ${JSON.stringify(indexFile)};
const CACHEABLE = ${CACHEABLE};
const ASSETS = 'ss-assets-v1', META = 'ss-meta', CODE = 'ss-code-' + VERSION;
const SCOPE = new URL('./', self.location).href;
let index = null;
async function loadIndex(fromNetwork) {
  const meta = await caches.open(META);
  let res = fromNetwork ? null : await meta.match(INDEX_URL);
  if (!res) { res = await fetch(INDEX_URL, { cache: 'no-cache' }); if (!res.ok) throw new Error('sw index ' + res.status); await meta.put(INDEX_URL, res.clone()); }
  return (index = await res.json());
}
const relOf = (url) => url.slice(SCOPE.length).replace(/[?#].*$/, '');
const isAsset = (rel) => /^(assets|vendor)\\//.test(rel) && CACHEABLE.test(rel);
/** Cache key of an asset: its URL + content hash (an unchanged file keeps its entry across deploys). */
function assetKey(rel, idx) { let r = rel; try { r = decodeURIComponent(rel); } catch {} const h = idx[r] || idx[rel]; return h ? SCOPE + rel + '?h=' + h : null; }
self.addEventListener('install', (e) => { e.waitUntil(loadIndex(true).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const idx = index || await loadIndex(false);
    const meta = await caches.open(META);
    for (const k of await meta.keys()) if (!k.url.endsWith('/' + INDEX_URL)) await meta.delete(k);
    const c = await caches.open(ASSETS);
    for (const k of await c.keys()) {   // key = <asset url>?h=<content hash>: drop changed / removed files only
      const u = new URL(k.url); const rel = u.href.slice(SCOPE.length).replace(/\\?.*$/, '');
      if (idx[rel] !== u.searchParams.get('h') && idx[decodeURIComponent(rel)] !== u.searchParams.get('h')) await c.delete(k);
    }
    for (const n of await caches.keys()) if (n.startsWith('ss-code-') && n !== CODE) await caches.delete(n);   // old builds' code
    await self.clients.claim();
  })());
});
/** Store one asset (full body) if it is in the index and not cached yet. @returns {Promise<boolean>} fetched */
async function store(url, init) {
  const rel = relOf(url);
  if (!isAsset(rel)) return false;
  const idx = index || await loadIndex(false).catch(() => ({}));
  const key = assetKey(rel, idx);
  if (!key) return false;
  const c = await caches.open(ASSETS);
  if (await c.match(key)) return false;
  const res = await fetch(SCOPE + rel, { ...init, cache: 'no-cache' });
  return usable(res) && keep(c, key, res);
}
/** SHA-1 of a body, first 12 hex digits (tools/build/sw.mjs index format). */
async function sha12(buf) {
  const d = new Uint8Array(await crypto.subtle.digest('SHA-1', buf));
  let h = ''; for (let i = 0; i < 6; i++) h += d[i].toString(16).padStart(2, '0');
  return h;
}
/**
 * Put a network response under its content-hash key, only if its bytes ARE that content: a copy served stale (the
 * browser's HTTP cache or a CDN edge still holding the previous deploy's file) would otherwise stay under the new key
 * for good (res: a usable() full response). @returns {Promise<boolean>} stored
 */
const usable = (res) => res.ok && res.status === 200 && res.type === 'basic';
async function keep(c, key, res) {
  const buf = await res.arrayBuffer();
  if (await sha12(buf) !== new URL(key).searchParams.get('h')) return false;
  await c.put(key, new Response(buf, { status: 200, statusText: res.statusText, headers: res.headers }));
  return true;
}
/** A cache miss: revalidate with the server (a cheap 304 when the browser's copy is current), never a stale copy. */
function fresh(req) {
  try { return fetch(new Request(req, { cache: 'no-cache' })); } catch { return fetch(req.url, { cache: 'no-cache' }); }
}
/** A cached full response → the 206 slice a media element asked for. */
async function slice(res, range) {
  const buf = await res.arrayBuffer(), n = buf.byteLength;
  const m = /bytes=(\\d*)-(\\d*)/.exec(range || '');
  let a = m && m[1] ? +m[1] : 0, b = m && m[2] ? +m[2] : n - 1;
  if (m && !m[1] && m[2]) { a = Math.max(0, n - +m[2]); b = n - 1; }
  b = Math.min(b, n - 1);
  if (a > b) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + n } });
  return new Response(buf.slice(a, b + 1), { status: 206, headers: { 'Content-Type': res.headers.get('Content-Type') || '', 'Content-Range': 'bytes ' + a + '-' + b + '/' + n, 'Content-Length': String(b - a + 1), 'Accept-Ranges': 'bytes' } });
}
async function asset(e, rel) {
  const req = e.request, range = req.headers.get('range');
  const idx = index || await loadIndex(false).catch(() => ({}));
  const key = assetKey(rel, idx);
  if (!key) return fetch(req);
  const c = await caches.open(ASSETS);
  const hit = await c.match(key);
  if (hit) return range ? slice(hit, range) : hit;
  if (range) { e.waitUntil(store(req.url).catch(() => {})); return fresh(req); }   // stream now, keep the whole file for next time
  const res = await fresh(req);
  if (usable(res)) e.waitUntil(keep(c, key, res.clone()).catch(() => {}));
  return res;
}
/** Code, HTML, manifests: network first (never stale), this build's copy when offline. */
async function code(req) {
  const key = req.mode === 'navigate' ? SCOPE + 'index.html' : req.url;
  try {
    const res = await fetch(req);
    if (res.ok && res.status === 200 && res.type === 'basic') {
      const copy = res.clone(), hashed = /[/]js[/][\\w.-]+-[A-Z0-9]{8}[.]js$/.test(key);   // content-hashed bundles: stored once
      caches.open(CODE).then(async (c) => { if (!hashed || !(await c.match(key))) await c.put(key, copy); }).catch(() => {});
    }
    return res;
  } catch (err) {
    const hit = await caches.open(CODE).then((c) => c.match(key));
    if (hit) return hit;
    throw err;
  }
}
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || !req.url.startsWith(SCOPE)) return;
  const rel = relOf(req.url);
  if (isAsset(rel)) return e.respondWith(asset(e, rel));
  if (req.mode === 'navigate' || /\\.(html|js|mjs|css|json|wasm)$/.test(rel)) return e.respondWith(code(req));
});
/** Page messages: cache-urls (what this page already loaded) / prefetch (a mission ahead, low priority) / status. */
self.addEventListener('message', (e) => {
  const d = e.data || {}, port = e.ports && e.ports[0];
  const reply = (m) => { try { port ? port.postMessage(m) : e.source && e.source.postMessage(m); } catch {} };
  if (d.type === 'cache-urls' || d.type === 'prefetch') {
    const urls = (d.urls || []).filter((u) => typeof u === 'string' && u.startsWith(SCOPE));
    const init = d.type === 'prefetch' ? { priority: 'low' } : undefined;
    e.waitUntil((async () => {
      let fetched = 0, i = 0;
      const worker = async () => { while (i < urls.length) { const u = urls[i++]; try { if (await store(u, init)) fetched++; } catch {} } };
      await Promise.all([worker(), worker(), worker()]);
      reply({ type: d.type, id: d.id, total: urls.length, fetched });
    })());
  } else if (d.type === 'status') {
    e.waitUntil((async () => { const c = await caches.open(ASSETS); reply({ type: 'status', id: d.id, version: VERSION, assets: (await c.keys()).length }); })());
  }
});
`;
}
