/**
 * Writes dist/sw.js + dist/sw-index-<hash>.json: a service worker that keeps the large, immutable-per-content assets
 * (models, textures, audio, fonts, decoders) in Cache Storage across visits, so a returning player doesn't pay
 * GitHub Pages' 10-minute max-age revalidation on hundreds of files.
 *
 * Never serves stale code: HTML, JS, CSS and JSON are not intercepted at all (network + HTTP cache as usual; JS is
 * content-hashed, CSS/JSON carry ?v=<version>). Cached assets are keyed by their content hash from the index, so
 * an asset that changes in a deploy misses the cache and is fetched fresh; entries not in the new index are purged
 * on activate. Range requests (video/audio streaming) pass through.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const CACHEABLE = /\.(glb|webp|jpe?g|png|hdr|ogg|mp3|woff2?|ttf|cube|wasm|svg)$/i;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...await walk(p)); else out.push(p);
  }
  return out;
}

export async function writeServiceWorker(out, info) {
  const index = {};
  for (const f of await walk(out)) {
    const rel = relative(out, f).split('\\').join('/');
    if (!CACHEABLE.test(rel) || !/^(assets|vendor)\//.test(rel)) continue;
    index[rel] = createHash('sha1').update(await readFile(f)).digest('hex').slice(0, 12);
  }
  const json = JSON.stringify(index);
  const ih = createHash('sha1').update(json).digest('hex').slice(0, 12);
  const indexFile = `sw-index-${ih}.json`;
  await writeFile(join(out, indexFile), json);
  await writeFile(join(out, 'sw.js'), swSource(info.short, indexFile));
  return { cached: Object.keys(index).length };
}

function swSource(version, indexFile) {
  return `/* SHADOW SIX asset cache, build ${version}. Generated by tools/build/sw.mjs. */
const INDEX_URL = ${JSON.stringify(indexFile)};
const CACHEABLE = ${CACHEABLE};
const ASSETS = 'ss-assets-v1', META = 'ss-meta';
const SCOPE = new URL('./', self.location).href;
let index = null;
async function loadIndex(fromNetwork) {
  const meta = await caches.open(META);
  let res = fromNetwork ? null : await meta.match(INDEX_URL);
  if (!res) { res = await fetch(INDEX_URL, { cache: 'no-cache' }); if (!res.ok) throw new Error('sw index ' + res.status); await meta.put(INDEX_URL, res.clone()); }
  return (index = await res.json());
}
self.addEventListener('install', (e) => { e.waitUntil(loadIndex(true).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const idx = index || await loadIndex(false);
    const meta = await caches.open(META);
    for (const k of await meta.keys()) if (!k.url.endsWith('/' + INDEX_URL)) await meta.delete(k);
    const c = await caches.open(ASSETS);
    for (const k of await c.keys()) {   // key = <asset url>?h=<content hash>
      const u = new URL(k.url); const rel = u.href.slice(SCOPE.length).replace(/\\?.*$/, '');
      if (idx[rel] !== u.searchParams.get('h')) await c.delete(k);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || req.headers.has('range') || !req.url.startsWith(SCOPE)) return;
  const rel = req.url.slice(SCOPE.length).replace(/[?#].*$/, '');
  if (!/^(assets|vendor)\\//.test(rel) || !CACHEABLE.test(rel)) return;   // JSON, code, video: untouched
  e.respondWith((async () => {
    const idx = index || await loadIndex(false).catch(() => ({}));
    const h = idx[decodeURIComponent(rel)] || idx[rel];
    if (!h) return fetch(req);
    const key = SCOPE + rel + '?h=' + h;
    const c = await caches.open(ASSETS);
    const hit = await c.match(key);
    if (hit) return hit;
    const res = await fetch(req);
    if (res.ok && res.status === 200 && res.type === 'basic') c.put(key, res.clone()).catch(() => {});
    return res;
  })());
});
`;
}
